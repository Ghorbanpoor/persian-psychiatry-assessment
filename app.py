def text_value(label, key, placeholder=""):
    return st.text_input(
        label,
        key=key,
        placeholder=placeholder
    )


def area_value(label, key, placeholder=""):
    return st.text_area(
        label,
        key=key,
        placeholder=placeholder
    )


def select_value(label, options, key):
    return st.selectbox(label, options, key=key)


def multi_value(label, options, key):
    return st.multiselect(label, options, key=key)


def yes_no(label, key):
    return st.radio(
        label,
        ["خیر", "بله", "نامشخص"],
        horizontal=True,
        key=key
    )


def add_section(title, description=None):
    st.markdown("---")
    st.subheader(title)
    if description:
        st.caption(description)


